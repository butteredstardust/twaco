// Generate the ThingWorx 10.2 catalogue from the 10.2.1 runtime bundle:
//   node scripts/generate_cds_icons.mjs <ptcswidgets.bundle.js>
// Only names are retained; no platform SVG content is copied. The catalogue is
// for 10.2, not a union of versions. Composer's cds.js contains an older subset.
import { readFileSync, writeFileSync } from "node:fs";

if (process.argv.length !== 3) {
  console.error("usage: node scripts/generate_cds_icons.mjs <ptcswidgets.bundle.js>");
  process.exit(2);
}
const bundle = readFileSync(process.argv[2], "utf8");
const start = bundle.indexOf('<ptcs-iconset-svg name="cds"');
const end = bundle.indexOf("</ptcs-iconset-svg>", start);
if (start < 0 || end < 0) throw new Error("CDS icon set is missing from the bundle");
// The bundle has 216 distinct icon_* IDs overall; icon_microphone belongs
// to chat-panel, not cds, and must not be accepted with the cds: prefix.
const names = [...new Set(
  [...bundle.slice(start, end).matchAll(/<g\s+id=["'](icon_[^"']+)["']/g)]
    .map(match => match[1])
)].sort();
if (names.length !== 215) throw new Error(`expected 215 ThingWorx 10.2.1 CDS icons, found ${names.length}`);
writeFileSync(new URL("../src/core/widgets/cds_icons.txt", import.meta.url),
  "# CDS icon names, ThingWorx 10.2 (10.2.1 runtime): Common/wc/lib/ptcswidgets.bundle.js\n" +
  "# Generated by scripts/generate_cds_icons.mjs; without the cds: prefix.\n" +
  names.join("\n") + "\n");
console.log(`Generated ${names.length} ThingWorx 10.2 CDS icon names`);
